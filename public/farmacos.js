window.buscarOpcoesMedicamento = function(texto, substanciaBase) {
  var limpo = (texto || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
  var subLimpa = (substanciaBase || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim();
  if (!limpo) return [];

  if (limpo.indexOf('insulina') !== -1 || subLimpa.indexOf('insulina') !== -1 || limpo.indexOf('lantus') !== -1 || limpo.indexOf('novorapid') !== -1 || limpo.indexOf('humalog') !== -1 || limpo.indexOf('tresiba') !== -1 || limpo.indexOf('toujeo') !== -1) {
    return window.VARIACOES.insulina;
  }
  for (var v in window.VARIACOES) {
    if (limpo.indexOf(v) !== -1) return window.VARIACOES[v];
  }
  for (var k in window.DOSAGENS_SIMPLES) {
    if (limpo.indexOf(k) !== -1) {
      return window.DOSAGENS_SIMPLES[k].map(function(d) {
        return { label: d, sub: substanciaBase || '' };
      });
    }
  }
  for (var s in window.DOSES_POR_SUBSTANCIA) {
    if (subLimpa.indexOf(s) !== -1 || limpo.indexOf(s) !== -1) {
      return window.DOSES_POR_SUBSTANCIA[s].map(function(d) {
        return { label: d, sub: substanciaBase || '' };
      });
    }
  }
  return [];
};
